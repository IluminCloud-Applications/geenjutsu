export class DeviceCatalogService {
  private static catalog: AndroidDeviceSpec[] = [...OFFICIAL_DEVICE_CATALOG];

  static getAll(): AndroidDeviceSpec[] {
    return this.catalog;
  }

  static getById(id: string): AndroidDeviceSpec | undefined {
    return this.catalog.find(d => d.id === id);
  }

  static getByBrand(brand: string): AndroidDeviceSpec[] {
    if (!brand || brand === 'all') return this.catalog;
    return this.catalog.filter(d => d.brand.toLowerCase() === brand.toLowerCase());
  }

  static getRandom(brand?: string, versionPrefix?: string): AndroidDeviceSpec {
    let list = brand && brand !== 'all' ? this.getByBrand(brand) : this.catalog;
    if (versionPrefix) {
      const filtered = list.filter(d => d.androidVersion.startsWith(versionPrefix));
      if (filtered.length > 0) {
        list = filtered;
      }
    }
    const pool = list.length > 0 ? list : this.catalog;
    const index = Math.floor(Math.random() * pool.length);
    return pool[index];
  }

  static toggleFavorite(id: string): AndroidDeviceSpec[] {
    this.catalog = this.catalog.map(d => {
      if (d.id === id) {
        return { ...d, isFavorite: !d.isFavorite };
      }
      return d;
    });
    return this.catalog;
  }
}
